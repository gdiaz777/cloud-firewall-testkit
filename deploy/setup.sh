#!/bin/bash
# Interactive setup: asks for the Check Point management (API key) and the AWS details, validates them and writes
# deploy/settings.env (chmod 600, not versioned). Re-run it to change any value (current values are the defaults).
#
# Prerequisite: a Check Point management reachable over the Management API with CME (e.g. a Smart-1 Cloud tenant)
# and an API key with read-write permissions. Every object this kit creates is prefixed and tagged.
. "$(dirname "$0")/lib.sh"
need curl jq openssl terraform ssh
[ -s "$SETTINGS" ] && { set -a; . "$SETTINGS"; set +a; }

ask() { # ask VAR "question" default [secret]
  local cur=${!1:-$3} v
  if [ "${4:-}" = secret ]; then
    read -r -s -p "  $2 [${cur:+********}]: " v; echo
  else read -r -p "  $2 [${cur}]: " v; fi
  printf -v "$1" '%s' "${v:-$cur}"
}

echo "${B}Firewall Testkit · setup${N}"
echo
echo "${B}1. Check Point management${N}"
echo "   Smart-1 Cloud: Infinity Portal → Smart-1 Cloud → Settings → API & SmartConsole (web API URL and API key)."
echo "   The URL looks like https://<tenant>.maas.checkpoint.com/<context-id>/web_api"
ask MGMT_URL "Management web API URL" ""
MGMT_URL=${MGMT_URL%/}; MGMT_URL=${MGMT_URL%/login}
ask MGMT_API_KEY "API key" "" secret
[ -n "$MGMT_URL" ] && [ -n "$MGMT_API_KEY" ] || die "URL and API key are required"
if cp_login; then ok "login OK (Management API $MGMT_API_VERSION)"; else die "cannot log in to $MGMT_URL"; fi
M=$(cme GET management | jq -r '.result.name // empty')
if [ -n "$M" ]; then ok "CME available, management name: $M"; CP_MANAGEMENT_NAME=$M
else warn "CME API not available: enter the management name configured in CME (autoprov-cfg)"; ask CP_MANAGEMENT_NAME "CME management name" "${CP_MANAGEMENT_NAME:-}"; fi
case "$MGMT_URL" in *maas.checkpoint.com*) MGMT_GW_ADDRESSES=0.0.0.0/0; ok "Smart-1 Cloud: gateways accept management ports from any source (no fixed IPs)";;
  *) ask MGMT_GW_ADDRESSES "Management public IP/CIDR (gateways allow management ports only from it)" "${MGMT_GW_ADDRESSES:-}";; esac
cp_logout

echo
echo "${B}2. AWS${N}  (the account should be dedicated to the lab)"
echo "   Credentials: an AWS CLI profile name, or the path to a .env file with AWS_ACCESS_KEY_ID / AWS_SECRET_ACCESS_KEY"
echo "   [/ AWS_SESSION_TOKEN] (e.g. SSO temporary credentials). Empty = credentials already in the environment."
CUR=${AWS_ENV_FILE:-${AWS_PROFILE:-}}
ask AWS_CREDS "AWS profile or .env path" "$CUR"
AWS_PROFILE=""; AWS_ENV_FILE=""
if [[ $AWS_CREDS =~ ^(AKIA|ASIA)[A-Z0-9]{12,}$ ]]; then die "that looks like an access key ID: give a profile name or the path to a .env file with the keys"
elif [ -n "$AWS_CREDS" ] && [ -f "${AWS_CREDS/#\~/$HOME}" ]; then AWS_ENV_FILE=$(realpath "${AWS_CREDS/#\~/$HOME}"); ok "credentials file: $AWS_ENV_FILE"
elif [ -n "$AWS_CREDS" ]; then AWS_PROFILE=$AWS_CREDS; ok "AWS profile: $AWS_PROFILE"; fi
ask AWS_REGION "Region" "${AWS_REGION:-eu-west-1}"
ask NAME_PREFIX "Name prefix (≤ 10 chars, lowercase)" "${NAME_PREFIX:-fwtk}"
[[ $NAME_PREFIX =~ ^[a-z][a-z0-9-]{1,9}$ ]] || die "invalid prefix"
MYIP=$(curl -s --max-time 5 https://checkip.amazonaws.com || true)
ask ADMIN_CIDR "Your public IP/CIDR (SSH to the test VMs and portal access)" "${ADMIN_CIDR:-${MYIP:+$MYIP/32}}"

echo
echo "${B}3. Check Point Cloud Firewall${N}"
ask GW_VERSION "Version and license" "${GW_VERSION:-R81.20-PAYG-NGTP}"
ask GW_INSTANCE_TYPE "Gateway instance type" "${GW_INSTANCE_TYPE:-c5n.xlarge}"
ask GW_MIN "Minimum gateways" "${GW_MIN:-2}"
ask GW_MAX "Maximum gateways" "${GW_MAX:-4}"
ask POLICY_PACKAGE "Policy package to create" "${POLICY_PACKAGE:-FW_Testkit}"
SIC_KEY=${SIC_KEY:-$(openssl rand -hex 12)}

umask 077
cat > "$SETTINGS" <<EOF
# Firewall Testkit settings (generated by deploy/setup.sh — contains secrets, do not commit)
MGMT_URL=$MGMT_URL
MGMT_API_KEY=$MGMT_API_KEY
CP_MANAGEMENT_NAME=$CP_MANAGEMENT_NAME
MGMT_GW_ADDRESSES=$MGMT_GW_ADDRESSES
AWS_PROFILE=$AWS_PROFILE
AWS_ENV_FILE=$AWS_ENV_FILE
AWS_REGION=$AWS_REGION
NAME_PREFIX=$NAME_PREFIX
ADMIN_CIDR=$ADMIN_CIDR
GW_VERSION=$GW_VERSION
GW_INSTANCE_TYPE=$GW_INSTANCE_TYPE
GW_MIN=$GW_MIN
GW_MAX=$GW_MAX
POLICY_PACKAGE=$POLICY_PACKAGE
SIC_KEY=$SIC_KEY
EOF
[ -s "$LAB" ] || command cp "$DEPLOY/lab.example.json" "$LAB"
echo
ok "settings saved to deploy/settings.env"
ok "lab design: deploy/state/lab.json (environments, segmentation matrix, roles, Internet targets) — edit it before deploying if needed"
echo "   Next: ${B}deploy/up.sh${N}   (add --run to launch the full test batch at the end)"
